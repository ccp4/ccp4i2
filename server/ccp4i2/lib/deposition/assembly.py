"""Crystal content and the biological assembly, from the model and the cell."""
import gemmi


def polymer_mass(structure):
    """Mass in Da of every polymer entity's full sequence, times its copies in
    the asymmetric unit (the deposited sequence, modelled or not)."""
    total = 0.0
    for ent in structure.entities:
        if ent.entity_type != gemmi.EntityType.Polymer or not ent.full_sequence:
            continue
        names = [gemmi.Entity.first_mon(m) for m in ent.full_sequence]
        mass = 0.0
        for name in names:
            info = gemmi.find_tabulated_residue(name)
            mass += info.weight if info is not None and info.weight > 0 else 110.0
        mass -= (len(names) - 1) * 18.015
        total += mass * max(1, len(ent.subchains))
    return total


def matthews(structure):
    """``(Vm in A^3/Da, solvent fraction)`` for the structure, or ``(None, None)``
    when the mass or cell is unknown."""
    mass = polymer_mass(structure)
    sg = structure.find_spacegroup()
    if mass <= 0 or sg is None or structure.cell.volume <= 0:
        return None, None
    z = len(sg.operations())
    vm = structure.cell.volume / (mass * z)
    return round(vm, 2), round((1.0 - 1.23 / vm) * 100.0, 1)


def operator_rows(cell, operators):
    """``_pdbx_struct_oper_list`` rows for a list of symmetry triplets
    (``"x,y,z"``, ``"-x+1,y,-z"``), the identity first whether or not given."""
    triplets = ["x,y,z"] + [t for t in operators if gemmi.Op(t) != gemmi.Op("x,y,z")]
    rows = []
    for idx, triplet in enumerate(triplets, start=1):
        op = gemmi.Op(triplet)
        rot = [[op.rot[i][j] / op.DEN for j in range(3)] for i in range(3)]
        tran = gemmi.Fractional(*[t / op.DEN for t in op.tran])
        vec = cell.orthogonalize(tran)
        # The rotation in Cartesian space: M_cart = F^-1 R F for fractional R.
        frac = cell.frac.mat
        orth = cell.orth.mat
        rmat = gemmi.Mat33(rot)
        cart = orth.multiply(rmat).multiply(frac).tolist()
        kind = "identity operation" if idx == 1 else "crystal symmetry operation"
        rows.append((idx, kind, "1_555" if idx == 1 else "?", op.triplet(),
                     _r(cart[0][0]), _r(cart[0][1]), _r(cart[0][2]), _r(vec.x),
                     _r(cart[1][0]), _r(cart[1][1]), _r(cart[1][2]), _r(vec.y),
                     _r(cart[2][0]), _r(cart[2][1]), _r(cart[2][2]), _r(vec.z)))
    return rows


def _r(value):
    return "%.6f" % float(value)


OPER_TAGS = ["id", "type", "name", "symmetry_operation",
             "matrix[1][1]", "matrix[1][2]", "matrix[1][3]", "vector[1]",
             "matrix[2][1]", "matrix[2][2]", "matrix[2][3]", "vector[2]",
             "matrix[3][1]", "matrix[3][2]", "matrix[3][3]", "vector[3]"]


def assembly_tables(structure, asym_ids, mode="asu", oligomeric_count=None,
                    operators=()):
    """The assembly categories as ``{category: (tags, rows)}``.

    ``mode`` is ``asu`` (the asymmetric unit is the assembly) or ``author``
    (the depositor's assembly: ``oligomeric_count`` copies, generated by
    ``operators`` applied to every asym id). ``_pdbx_struct_assembly.details``
    is the enumerated ``author_defined_assembly``; the evidence goes in
    ``_pdbx_struct_assembly_auth_evidence`` (OneDep ignores method_details).
    """
    asym_list = ",".join(asym_ids)
    if mode != "author":
        count = sum(1 for e in structure.entities
                    if e.entity_type == gemmi.EntityType.Polymer for _ in e.subchains)
        oper_rows = operator_rows(structure.cell, [])
        assembly = (1, "author_defined_assembly", _oligo_word(count), count)
        gen = [(1, "1", asym_list)]
    else:
        oper_rows = operator_rows(structure.cell, list(operators))
        expression = ",".join(str(r[0]) for r in oper_rows)
        count = int(oligomeric_count or 0)
        assembly = (1, "author_defined_assembly", _oligo_word(count), count or "?")
        gen = [(1, expression, asym_list)]
    return {
        "_pdbx_struct_assembly": (
            ["id", "details", "oligomeric_details", "oligomeric_count"], [assembly]),
        "_pdbx_struct_assembly_gen": (["assembly_id", "oper_expression", "asym_id_list"], gen),
        "_pdbx_struct_oper_list": (OPER_TAGS, oper_rows),
    }


_OLIGO = {1: "monomeric", 2: "dimeric", 3: "trimeric", 4: "tetrameric", 5: "pentameric",
          6: "hexameric", 7: "heptameric", 8: "octameric", 9: "nonameric", 10: "decameric",
          12: "dodecameric", 24: "24-meric"}


def _oligo_word(count):
    return _OLIGO.get(int(count or 0), "%d-meric" % int(count or 0) if count else "?")
