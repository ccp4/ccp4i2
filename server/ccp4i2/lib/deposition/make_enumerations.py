"""Regenerate ``_enumerations_data.py``, the vendored copy of the controlled
vocabularies the deposition task writes.

Sources, both shipped with CCP4:

- ``$CCP4/share/pdb-extract-data/cif_enumerate.list``: pdb_extract's list of
  allowed values per mmCIF item (blocks separated by blank lines; the first
  line names the item, the rest are its values). The best offline proxy for
  the menus of OneDep's deposition form.
- the PDBx dictionary, for the few items the task writes that the list does
  not cover (``_pdbx_struct_assembly_auth_evidence``,
  ``_pdbx_initial_refinement_model``, ``_pdbx_entity_instance_feature``).
  ``mmcif_pdbx_v5_next.dic.gz`` first, then ``libcifpp/mmcif_pdbx.dic`` for
  an item the former does not enumerate.

Run with ccp4-python from the server directory:

    ccp4-python -m ccp4i2.lib.deposition.make_enumerations

and commit the regenerated file. ``enumerations.py`` reads the CCP4 list
itself when it is there, so a newer CCP4 takes effect without regenerating;
the vendored copy is what a CCP4-free server and the form's sub-item menus
use, and the unit tests check the two agree.
"""
import os
import pprint
import sys

# Items the task writes whose values are controlled.
LIST_ITEMS = (
    "_struct_keywords.pdbx_keywords",
    "_software.name",
    "_software.classification",
    "_refine.pdbx_method_to_determine_struct",
    "_diffrn_radiation.pdbx_diffrn_protocol",
    "_diffrn_radiation.pdbx_monochromatic_or_laue_m_l",
    "_diffrn_radiation.pdbx_scattering_type",
    "_diffrn_source.source",
    "_diffrn_source.type",
    "_diffrn_source.pdbx_synchrotron_site",
    "_diffrn_source.pdbx_synchrotron_beamline",
    "_diffrn_detector.detector",
    "_diffrn_detector.type",
    "_exptl_crystal_grow.method",
    "_exptl.method",
    "_pdbx_contact_author.country",
    "_pdbx_contact_author.name_salutation",
    "_pdbx_contact_author.role",
    "_pdbx_contact_author.organization_type",
    "_pdbx_database_related.db_name",
    "_pdbx_database_related.content_type",
    "_entity.type",
    "_entity.src_method",
    "_entity_src_gen.pdbx_seq_type",
    "_entity_src_gen.pdbx_alt_source_flag",
    "_pdbx_entity_src_syn.pdbx_alt_source_flag",
    "_citation.unpublished_flag",
)
DICTIONARY_ITEMS = (
    "_pdbx_struct_assembly_auth_evidence.experimental_support",
    "_pdbx_initial_refinement_model.type",
    "_pdbx_initial_refinement_model.source_name",
    "_pdbx_entity_instance_feature.feature_type",
)


def parse_enumerate_list(text):
    """``{item: [values]}`` from the text of ``cif_enumerate.list``."""
    out = {}
    for block in text.split("\n\n"):
        lines = [line.rstrip("\r") for line in block.strip("\n").split("\n") if line.strip()]
        if not lines or not lines[0].startswith("_"):
            continue
        out[lines[0].strip()] = [v.strip() for v in lines[1:]]
    return out


def dictionary_enumerations(paths, items):
    import gemmi

    out = {}
    for path in paths:
        if not os.path.exists(path):
            continue
        frame_block = gemmi.cif.read(path).sole_block()
        for item in items:
            if item in out:
                continue
            frame = frame_block.find_frame(item)
            if frame is None:
                continue
            values = [r.str(0) for r in frame.find("_item_enumeration.", ["value"])]
            if values:
                out[item] = values
    return out


def main(ccp4=None):
    ccp4 = ccp4 or os.environ.get("CCP4")
    if not ccp4:
        sys.exit("source the CCP4 setup first")
    share = os.path.join(ccp4, "share")
    with open(os.path.join(share, "pdb-extract-data", "cif_enumerate.list")) as handle:
        listed = parse_enumerate_list(handle.read())
    data = {item: listed[item] for item in LIST_ITEMS if item in listed}
    missing = [item for item in LIST_ITEMS if item not in listed]
    data.update(dictionary_enumerations(
        [os.path.join(share, "pdb-extract-data", "mmcif_pdbx_v5_next.dic.gz"),
         os.path.join(share, "libcifpp", "mmcif_pdbx.dic")], DICTIONARY_ITEMS))
    missing += [item for item in DICTIONARY_ITEMS if item not in data]
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_enumerations_data.py")
    with open(target, "w") as handle:
        handle.write('"""Generated by make_enumerations.py from %s -- do not edit."""\n\n'
                     % os.path.basename(os.path.normpath(ccp4)))
        handle.write("ENUMERATIONS = ")
        handle.write(pprint.pformat({k: tuple(v) for k, v in sorted(data.items())}, width=100))
        handle.write("\n")
    print("wrote %s: %d items%s" % (target, len(data),
                                     "; not found: " + ", ".join(missing) if missing else ""))


if __name__ == "__main__":
    main()
