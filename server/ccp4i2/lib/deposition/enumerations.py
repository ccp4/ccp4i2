"""The one source of the controlled values the deposition task writes.

``allowed(item)`` gives the values OneDep accepts for an mmCIF item: from
pdb_extract's ``cif_enumerate.list`` in the CCP4 installation when there is
one (read lazily, once), else from the vendored copy ``_enumerations_data``
(regenerated by ``make_enumerations.py``). The task's menus, its
``validity()`` and the final gate over the written file all ask here, so
they cannot disagree.

``canonical(item, value)`` maps what a user or a lineage file says to the
PDB's spelling when the mapping is obvious (case, a vendor prefix on a
detector, a facility's long name), else returns None.
"""
import os
import re
from functools import lru_cache

from ._enumerations_data import ENUMERATIONS as _VENDORED


def _ccp4_list_path():
    ccp4 = os.environ.get("CCP4")
    if not ccp4:
        return None
    path = os.path.join(ccp4, "share", "pdb-extract-data", "cif_enumerate.list")
    return path if os.path.exists(path) else None


@lru_cache(maxsize=1)
def _table():
    """``{item: tuple(values)}``: the vendored table, overlaid with the CCP4
    list for every item that list has."""
    table = dict(_VENDORED)
    path = _ccp4_list_path()
    if path:
        from .make_enumerations import parse_enumerate_list

        try:
            with open(path) as handle:
                listed = parse_enumerate_list(handle.read())
            for item in table:
                if item in listed and listed[item]:
                    table[item] = tuple(listed[item])
        except OSError:
            pass
    return table


def source():
    """Where the values come from: the CCP4 list's path, or 'vendored'."""
    return _ccp4_list_path() or "vendored"


def items():
    return tuple(_table())


def allowed(item):
    """The allowed values of an mmCIF item, or None when it is not controlled."""
    values = _table().get(item)
    return tuple(values) if values else None


def is_allowed(item, value):
    values = allowed(item)
    return values is None or value in values


# Facilities as people write them -> the PDB's _diffrn_source.pdbx_synchrotron_site.
_SITE_ALIASES = {
    "diamond light source": "Diamond", "diamond light source ltd": "Diamond", "dls": "Diamond",
    "european synchrotron radiation facility": "ESRF", "esrf-ebs": "ESRF",
    "swiss light source": "SLS", "advanced photon source": "APS",
    "advanced light source": "ALS", "stanford synchrotron radiation lightsource": "SSRL",
    "canadian light source": "CLSI", "cls": "CLSI", "petra iii": "PETRA III, DESY",
    "petra 3": "PETRA III, DESY", "desy": "PETRA III, DESY", "bessy ii": "BESSY",
    "max iv": "MAX IV", "maxiv": "MAX IV", "nsls-ii": "NSLS-II", "nsls ii": "NSLS-II",
    "spring8": "SPring-8", "spring 8": "SPring-8", "pf": "Photon Factory", "kek": "Photon Factory",
    "shanghai synchrotron radiation facility": "SSRF", "australian synchrotron (ansto)": "Australian Synchrotron",
    "lcls": "SLAC LCLS", "elettra": "ELLETTRA", "alba synchrotron": "ALBA",
}


def _norm(text):
    return re.sub(r"[\s_\-]+", " ", str(text or "").strip()).lower()


def canonical(item, value):
    """The PDB's spelling of ``value`` for ``item``, or None when none is obvious.

    Exact and case-insensitive matches always; then per item: a detector
    type without its vendor prefix ("Pilatus 6M-F" -> "DECTRIS PILATUS 6M-F"),
    a facility's long name ("Diamond Light Source" -> "Diamond"), hyphen and
    space variants.
    """
    if value is None or str(value).strip() == "":
        return None
    values = allowed(item)
    text = str(value).strip()
    if values is None:
        return text
    if text in values:
        return text
    by_norm = {_norm(v): v for v in values}
    if _norm(text) in by_norm:
        return by_norm[_norm(text)]
    if item == "_diffrn_source.pdbx_synchrotron_site":
        alias = _SITE_ALIASES.get(_norm(text))
        if alias:
            return canonical(item, alias) or (alias if alias in values else None)
    if item == "_diffrn_detector.type":
        hits = [v for v in values if _norm(v).endswith(" " + _norm(text))]
        if len(hits) == 1:
            return hits[0]
    if item == "_diffrn_source.pdbx_synchrotron_beamline":
        compact = {_norm(v).replace(" ", ""): v for v in values}
        if _norm(text).replace(" ", "") in compact:
            return compact[_norm(text).replace(" ", "")]
    return None


def source_type(site, beamline):
    """The enumerated ``_diffrn_source.type`` for a synchrotron site and
    beamline ("DIAMOND BEAMLINE I02"), or None when the combination is not
    in the list."""
    if not site or not beamline:
        return None
    candidate = "%s BEAMLINE %s" % (str(site).upper(), str(beamline).upper())
    values = allowed("_diffrn_source.type") or ()
    by_norm = {_norm(v): v for v in values}
    return by_norm.get(_norm(candidate))


# Items the gate does not fail on: program names beyond the list are written
# on purpose (with a warning), because the archive records what was used.
GATE_EXEMPT = ("_software.name",)


def violations(block, categories):
    """``[(item, value)]`` for every value in the written ``categories`` of
    ``block`` that the source does not allow: the gate after writing."""
    import gemmi

    wanted = {c.lstrip("_") for c in categories}
    out = []
    for item in items():
        if item in GATE_EXEMPT:
            continue
        category = item.split(".")[0].lstrip("_")
        if category not in wanted:
            continue
        values = allowed(item)
        for raw in block.find_values(item):
            if raw in ("?", "."):
                continue
            value = gemmi.cif.as_string(raw)
            if value not in values:
                out.append((item, value))
    return out
