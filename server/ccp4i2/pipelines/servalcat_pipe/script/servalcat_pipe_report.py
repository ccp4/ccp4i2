    def addOutlierLinks(self, parent=None, limit=12, per_kind=5, clash_limit=8):
        """The worst outliers as buttons that open Moorhen on each (the job's
        outlierScene), a group for each judge of the model: Servalcat's
        geometry, MolProbity's residues (a group per kind, so one numerous
        kind does not hide the rest) and clashes, the ADP analysis. An open
        viewer of this project takes the click and moves there, so they can be
        stepped through."""
        from ccp4i2.pipelines.servalcat_pipe.script.outlier_places import (
            MOLPROBITY_SECTIONS, adp_places, describe, molprobity_places, worst)
        if parent is None:
            parent = self
        groups = []
        try:
            groups.append(("Geometry (Servalcat): largest |Z| first", worst(self.xmlnode, limit=limit)))
        except Exception:
            pass
        try:
            molprobity = molprobity_places(self.xmlnode)
        except Exception:
            molprobity = []
        for _, kind, title, _ in MOLPROBITY_SECTIONS:
            groups.append((f"MolProbity: {title} outliers",
                           [p for p in molprobity if p["kind"] == kind][:per_kind]))
        groups.append(("MolProbity: clashes, largest overlap first",
                       [p for p in molprobity if p["kind"] == "clash"][:clash_limit]))
        try:
            groups.append(("ADPs outside the limits: furthest outside first", adp_places(self.xmlnode)[:limit]))
        except Exception:
            pass
        groups = [(title, found) for title, found in groups if found]
        if not groups:
            return
        fold = parent.addFold(label="Look at the outliers in Moorhen", brief="Outliers in Moorhen",
                              initiallyOpen=True)
        fold.addText(text=(
            "Each opens the refined model and its maps centred on the outlier, its residues and atoms "
            "marked in magenta; with a viewer of this project already open, the click moves that viewer "
            "rather than opening another."))
        for title, found in groups:
            fold.addText(text=title, tone="heading")
            for place in found:
                fold.addMoorhenLink(label=describe(place), method="outlierScene",
                                    kwargs={"kind": place["kind"], "index": place["index"]})

    def validationReport(self, parent=None):
        if parent is None:
            parent = self
        try:
            validateReport = None
            if len(self.xmlnode.findall(".//Validation")) > 0:
                validateReportNode = self.xmlnode.findall(".//Validation")[0]
                if validateReportNode is not None:
                    validateReport = validate_protein_report.validate_protein_report(xmlnode=validateReportNode, jobStatus='nooutput', jobInfo=self.jobInfo)
                    try:
                        if len(validateReportNode.findall ( ".//Iris" )) > 0:
                            if validateReportNode.findall ( ".//Iris" )[0].text != "":
                                irisFold = parent.addFold ( label="Iris validation report", initiallyOpen=False, brief='Iris' )
                                irisdiv = irisFold.addDiv()
                                validateReport.add_iris_panel(parent=irisFold)
                    except:
                        self.addText("Warning - Iris validation report failed")

            if len(self.xmlnode.findall(".//ADP_ANALYSIS")) > 0:
                adpFold = parent.addFold(label='ADP analysis', initiallyOpen=False, brief='ADP')
                self.addAdpAnalysis(adpFold=adpFold)

            if validateReport is not None:
                try:
                    if len(validateReportNode.findall ( ".//Molprobity" )) > 0:
                        if validateReportNode.findall ( ".//Molprobity" )[0].text != "":
                            molprobityFold = parent.addFold ( label="MolProbity analysis", initiallyOpen=False )
                            validateReport.add_molprobity(parent=molprobityFold)
                except:
                    self.addText("Warning - MolProbity analysis failed")

                try:
                    if len(validateReportNode.findall ( ".//Ramachandran" )) > 0:
                        if validateReportNode.findall ( ".//Ramachandran" )[0].text != "":
                            ramachandranFold = parent.addFold ( label="Ramachandran plots", initiallyOpen=False )
                            validateReport.add_ramachandran(parent=ramachandranFold)
                except:
                    self.addText("Warning - Ramachandran plot generation failed")           

        except:
            traceback.print_exc()
        clearingDiv = self.addDiv()


